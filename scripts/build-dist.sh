#!/usr/bin/env bash
# Build the single-file distribution on stdout: lib/*.sh in order, the advisory data
# embedded as a here-document, and the entry call. Used by "make dist".
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
data="$root/data/advisories.tsv"
version=$(sed -n 's/^BCC_VERSION="\(.*\)"$/\1/p' "$root/lib/main.sh")

if grep -qx 'BCC_DATA_EOF' "$data"; then
  echo "build-dist: data file contains the here-document delimiter" >&2
  exit 1
fi

cat <<EOF
#!/usr/bin/env bash
# brotli-cve-check $version - read-only local check for CVE-2026-111497 (Brotli decoder).
# Single-file build of https://github.com/sakai-sktech/brotli-check (generated by "make dist";
# edit lib/*.sh and data/advisories.tsv instead). Verify it against SHA256SUMS and read it
# before running it.
#
# SPDX-License-Identifier: MIT
# Copyright (c) 2026 株式会社ジェイ・メディック
# shellcheck disable=SC2317  # callbacks are invoked by name (bcc_find_each)
set -u
set -o pipefail
EOF

for f in "$root"/lib/*.sh; do
  printf '\n# ---- %s ----\n' "lib/${f##*/}"
  grep -v '^# shellcheck shell=bash$' "$f"
done

printf '\n# ---- data/advisories.tsv ----\n'
printf 'bcc_embedded_data() {\n  cat <<'"'"'BCC_DATA_EOF'"'"'\n'
cat "$data"
printf 'BCC_DATA_EOF\n}\n\nbcc_main "$@"\n'
